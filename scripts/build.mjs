// Builds the platform outputs from the shared engine (src/engine.ts) and rules (rules/rules.json):
//   chrome-extension/sporfri.js     — engine + rules, sets globalThis.Sporfri
//   chrome-extension/main-world.js  — engine + rules + src/chrome-main-world.js (page world)
//   ios/Sporfri.js                  — single-file Scriptable script
// The TypeScript types are stripped with Node's built-in stripTypeScriptTypes — no dependencies.
// Pass --install-ios to also copy the Scriptable script into iCloud Drive/Scriptable.
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
const write = (p, lines) => writeFileSync(join(root, p), lines.join('\n') + '\n');
const banner = '// GENERATED by scripts/build.mjs from src/ and rules/ — do not edit directly.';

/** TypeScript module → plain JS statements plus the list of exported names. */
function compileEngine(source) {
  // Stripping replaces types with spaces. Tidying those up is only safe if the source itself
  // never has two spaces in a row inside code (which could be in a string or regex).
  if (/\S {2,}/.test(source.replace(/^\s*(\/\/|\/?\*).*$/gm, ''))) {
    throw new Error('src/engine.ts: avoid runs of spaces inside code lines (the build tidies them)');
  }
  const unsupported = source.match(/^export (?!function |const |interface |type ).*/m);
  if (unsupported) throw new Error(`src/engine.ts: unsupported export form: ${unsupported[0]}`);

  const names = [...source.matchAll(/^export (?:function|const) (\w+)/gm)].map((m) => m[1]);
  const js = stripTypeScriptTypes(source)
    .replace(/^export /gm, '')
    .replace('// ---------- Types ----------', '')
    .replace(/(\S) {2,}(?=[(),;\]])/g, '$1')
    .replace(/(\S) {2,}/g, '$1 ')
    .replace(/[ \t]+$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  return { js, names };
}

const engine = compileEngine(read('src/engine.ts'));
const rules = JSON.parse(read('rules/rules.json'));

// Expression evaluating to { ...engine, ...createCleaner(RULES), RULES }.
const sporfriExpr = [
  '(() => {',
  "'use strict';",
  engine.js,
  `const RULES = ${JSON.stringify(rules)};`,
  `return Object.assign({ ${engine.names.join(', ')} }, createCleaner(RULES), { RULES });`,
  '})()',
];

write('chrome-extension/sporfri.js', [banner, 'globalThis.Sporfri = ' + sporfriExpr[0], ...sporfriExpr.slice(1), ';']);

// Chrome injects a given file only once per frame, so the MAIN-world script gets its own bundle.
// It's wrapped so nothing leaks into the page's globals.
write('chrome-extension/main-world.js', [
  banner,
  '(() => {',
  'const Sporfri = ' + sporfriExpr[0], ...sporfriExpr.slice(1), ';',
  read('src/chrome-main-world.js'),
  '})();',
]);

write('ios/Sporfri.js', [
  '// Variables used by Scriptable.',
  '// These must be at the top of the file. Do not edit.',
  '// icon-color: deep-green; icon-glyph: shoe-prints;',
  banner,
  'const Sporfri = ' + sporfriExpr[0], ...sporfriExpr.slice(1), ';',
  '',
  read('src/scriptable-main.js'),
]);

console.log('Built chrome-extension/{sporfri,main-world}.js and ios/Sporfri.js');

if (process.argv.includes('--install-ios')) {
  const icloud = join(homedir(), 'Library/Mobile Documents/iCloud~dk~simonbs~Scriptable/Documents');
  if (!existsSync(icloud)) {
    console.error(`Scriptable iCloud folder not found:\n  ${icloud}\nInstall Scriptable on your iPhone (with iCloud on) or copy ios/Sporfri.js manually.`);
    process.exit(1);
  }
  copyFileSync(join(root, 'ios/Sporfri.js'), join(icloud, 'Sporfri.js'));
  console.log(`Installed to ${icloud}/Sporfri.js — it will sync to Scriptable on your iPhone.`);
}
